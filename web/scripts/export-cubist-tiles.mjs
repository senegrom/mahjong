import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { TILE_TYPES, tileFile } from '../src/lib/tiles.js';

// Mechanical lossless extraction of the exact A–E selected from study 02.
// Run from any directory: node web/scripts/export-cubist-tiles.mjs
const root = fileURLToPath(new URL('../../', import.meta.url));
const out = path.join(root, 'web/public/tiles/cubist');
const source = 'docs/design/cubist/studies/02-further-studies.png';
const sourceSha256 = createHash('sha256').update(readFileSync(path.join(root, source))).digest('hex');
const facePresentation = { radius: 26, bleed: 3, preserveAspectRatio: 'none' };
const definitions = [
  ['A', '3p', 'Three disks', [36, 104, 373, 491]],
  ['B', '5s', 'Five bamboo', [441, 104, 372, 491]],
  ['C', '9m', 'Nine characters', [845, 104, 374, 491]],
  ['D', '1z', 'East wind', [36, 656, 372, 497]],
  ['E', '5z', 'White dragon', [441, 656, 372, 497]],
];
const manifest = {
  version: 1, name: 'Cubist', id: 'cubist',
  canvas: { width: 300, height: 400 }, facePresentation,
  source, sourceSha256,
  approval: 'Carl selected all but F from study 02 and requested deployment.',
  fallback: 'classic',
  tiles: [],
  rejected: [{ candidate: 'F', tile: '6z', label: 'Green dragon', source }],
};
mkdirSync(path.join(out, 'approved'), { recursive: true });
for (const [candidate, tile, label, crop] of definitions) {
  const name = tileFile(tile);
  const [x, y, width, height] = crop;
  const png = `approved/${name}.png`, svg = `approved/${name}.svg`;
  const raster = execFileSync('convert', [path.join(root, source), '-crop', `${width}x${height}+${x}+${y}`, '+repage', '-strip', 'PNG:-'], { maxBuffer: 8 * 1024 * 1024 });
  writeFileSync(path.join(out, png), raster);
  const { radius, bleed, preserveAspectRatio } = facePresentation;
  const verticalBleed = bleed * 4 / 3;
  writeFileSync(path.join(out, svg), `<svg xmlns="http://www.w3.org/2000/svg" width="300" height="400" viewBox="0 0 300 400" role="img" aria-labelledby="title"><title id="title">${label} — Cubist</title><defs><clipPath id="face"><rect width="300" height="400" rx="${radius}"/></clipPath></defs><image clip-path="url(#face)" x="${-bleed}" y="${-verticalBleed}" width="${300 + 2 * bleed}" height="${400 + 2 * verticalBleed}" preserveAspectRatio="${preserveAspectRatio}" href="data:image/png;base64,${raster.toString('base64')}"/></svg>\n`);
  manifest.tiles.push({ candidate, tile, name, label, status: 'approved', png, svg,
    crop: { x, y, width, height }, pngSha256: createHash('sha256').update(raster).digest('hex') });
}
const approved = manifest.tiles.map(entry => entry.tile);
manifest.remaining = TILE_TYPES.filter(tile => !approved.includes(tile));
writeFileSync(path.join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
writeFileSync(path.join(root, 'web/src/lib/cubist-faces.js'), `// Generated by web/scripts/export-cubist-tiles.mjs. Study 02, candidates A–E only.\nexport const CUBIST_APPROVED = Object.freeze(${JSON.stringify(approved)});\n`);

const gallery = manifest.tiles.map(entry => `<figure><img src="${entry.svg}" alt="${entry.label}" width="300" height="400"><figcaption>${entry.candidate} · ${entry.label}</figcaption></figure>`).join('');
const hand = ['3p', '3p', '5s', '5s', '9m', '9m', '1z', '1z', '5z', '5z', '6z', '7s', '2m', '8p'];
const rack = hand.map(tile => {
  const entry = manifest.tiles.find(entry => entry.tile === tile);
  return `<img src="${entry ? entry.svg : `../${tileFile(tile)}.svg`}" alt="${entry?.label ?? tile}" width="300" height="400">`;
}).join('');
writeFileSync(path.join(out, 'preview.html'), `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Cubist Mahjong — Approved Tiles</title>
<style>*{box-sizing:border-box}body{margin:0;background:#f4f0e6;color:#252923;font:16px/1.5 system-ui,sans-serif}main{max-width:1000px;margin:auto;padding:32px 20px 56px}h1{font:48px/1.1 Georgia,serif;margin:8px 0 16px}h2{font-size:22px;margin:36px 0 16px}p{max-width:680px}a{color:inherit}.gallery{display:grid;grid-template-columns:repeat(auto-fit,minmax(150px,1fr));gap:24px}figure{margin:0}figure img{width:100%;height:auto;display:block}figcaption{font-size:14px;margin-top:8px}.scroll{overflow-x:auto;padding:12px 4px 24px}.rack{display:flex;gap:2px;width:390px;padding:20px 12px;background:#173d34;border-radius:12px}.rack img{width:calc((100% - 26px)/14);height:auto;aspect-ratio:3/4;min-width:0;flex:none;border-radius:2px}.notes{color:#646a60;font-size:14px}select{font:inherit;padding:6px;background:#fff;border:1px solid #aaa;border-radius:6px}@media(max-width:500px){main{padding:24px 16px}.gallery{grid-template-columns:repeat(2,minmax(0,1fr))}}</style></head>
<body><main><a href="../../">← Mahjong</a><h1>Cubist</h1><p>Five approved faces from Further Studies. Select <strong>Options → Tile face → Cubist</strong> in the game. The remaining tiles use Classic artwork.</p>
<h2>Approved artwork</h2><div class="gallery">${gallery}</div>
<h2>A mixed hand</h2><label>Hand width <select id="width"><option value="390">390 px · compact</option><option value="844">844 px · landscape</option></select></label><div class="scroll"><div class="rack" id="rack">${rack}</div></div>
<p class="notes">The last four tiles demonstrate Classic artwork for identities awaiting Cubist approval. Green dragon F is excluded. The white dragon keeps its blank centre when dora; it receives the normal red ring and foil sheen.</p>
<p class="notes">The exact selected source pixels are preserved in lossless PNG crops. SVG wrappers use the shared 300 × 400 canvas and rounded clipping. <a href="manifest.json">Export manifest</a></p></main>
<script>document.getElementById('width').addEventListener('change',event=>{document.getElementById('rack').style.width=event.target.value+'px'});</script></body></html>\n`);
console.log(`Exported ${approved.length} approved Cubist faces; ${manifest.remaining.length} identities use Classic artwork.`);
