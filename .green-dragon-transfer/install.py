from pathlib import Path
import base64, hashlib, json, re, subprocess

root=Path.cwd()
transfer=root/'.green-dragon-transfer'
sha=lambda b:hashlib.sha256(b).hexdigest()
def read(p): return (root/p).read_text(encoding='utf-8')
def put(p,text):
    f=root/p; f.parent.mkdir(parents=True,exist_ok=True); f.write_text(text,encoding='utf-8')
def once(text,old,new):
    assert text.count(old)==1, (old,text.count(old))
    return text.replace(old,new,1)
manifest_path='web/public/tiles/van-gogh/manifest.json'
previous=json.loads(read(manifest_path))
assert '6z' in previous['remaining']
assert len(previous['tiles'])==30
assert not any(t['tile']=='6z' for t in previous['tiles'])
art_paths=[p for p in subprocess.check_output(['git','ls-files','docs/design','web/public/tiles'],text=True).splitlines() if Path(p).suffix.lower() in {'.png','.webp','.svg','.avif','.jpg','.jpeg'}]
preserved={p:sha((root/p).read_bytes()) for p in art_paths}
hand=lambda s:re.search(r'<div class="rack" id="rack">([\s\S]*?)</div>',s).group(1)
old_hand=hand(read('web/public/tiles/van-gogh/preview.html'))
assert old_hand.count('<img ')==14
ready=json.loads((transfer/'ready.json').read_text())
parts=[]
for part in ready['parts']:
    data=(transfer/part['file']).read_bytes()
    assert len(data)==part['size'] and sha(data)==part['sha256'],part['file']
    parts.append(data)
raster=b''.join(parts)
assert sha(raster)==ready['rasterSha256']
assert raster[4:8]==b'ftyp' and b'avif' in raster[:32]
svg=('<svg xmlns="http://www.w3.org/2000/svg" width="300" height="400" viewBox="0 0 300 400" role="img" aria-labelledby="title"><title id="title">Green dragon — Van Gogh</title><defs><clipPath id="face"><rect width="300" height="400" rx="26"/></clipPath></defs><image clip-path="url(#face)" x="-3" y="-4" width="306" height="408" preserveAspectRatio="none" href="data:image/avif;base64,'+base64.b64encode(raster).decode()+'"/></svg>\n')
assert sha(svg.encode())==ready['svgSha256']
provenance=json.loads((transfer/'provenance.json').read_text())
assert provenance['svgSha256']==ready['svgSha256']
assert provenance['rasterSha256']==ready['rasterSha256']
source=provenance['source']
assert not (root/source).exists()
put(source,svg)
put('docs/design/van-gogh/green-dragon-vineyard.json',json.dumps(provenance,ensure_ascii=False,indent=2)+'\n')
put('web/tests/van-gogh-green-dragon.test.js',(transfer/'green-dragon.test.js').read_text())
export_path='web/scripts/export-van-gogh-tiles.mjs'
export=read(export_path)
export=once(export,'\n};\nconst definitions = [\n',f"\n  greenDragonVineyard: '{source}',\n}};\nconst definitions = [\n")
export=once(export,'\n];\nconst onlyArgument',"\n  ['Vineyard Dragon C', '6z', 'Green dragon', 'greenDragonVineyard', [0, 0, 300, 400]],\n];\nconst onlyArgument")
new_approval='Carl explicitly selected C, Green Dragon at the Vineyard, from the first green-dragon board for 6z / Hatsu and requested deployment. Preserve its green dragon, blue sky and golden vineyard without recolouring. The later mountain, vase, cypress and iris alternatives are not selected. The exact 450 x 600 crop is uniformly reduced to 300 x 400, with no stretching.'
export,n=re.subn(r"(^  approval: '[^\n]*)',\n",lambda m:m.group(1)+' '+new_approval+"',\n",export,count=1,flags=re.M)
assert n==1
export=once(export,'// Generated by web/scripts/export-van-gogh-tiles.mjs. Includes ','// Generated by web/scripts/export-van-gogh-tiles.mjs. Includes Green Dragon at the Vineyard C (6z), ')
export=once(export,'approved faces, including Lemons by the Sea','approved faces, including Green Dragon at the Vineyard C for green dragon, Lemons by the Sea')
put(export_path,export)
test_path='web/tests/tile-faces.test.js'
tests=read(test_path)
tests=once(tests,"'7p', '9m', '8p'];","'7p', '9m', '8p', '6z'];")
tests=once(tests,"'Poppies B (smaller Wan)', 'Eight Lemons']);","'Poppies B (smaller Wan)', 'Eight Lemons', 'Vineyard Dragon C']);")
tests=once(tests,"tile === '9m' ? 'image/avif' : 'image/webp'","['9m', '6z'].includes(tile) ? 'image/avif' : 'image/webp'")
tests=once(tests,"'4p', '8m', '6p']) {","'4p', '8m', '6p', '6z']) {")
put(test_path,tests)
section='''\n## Green Dragon at the Vineyard C — green dragon\n\nCarl selected **C from the first green-dragon board**, the green dragon flying above a golden vineyard and village, as **6z / Hatsu**. The later mountain/pine dragon, vase, cypress and iris alternatives are not used. The explicitly approved colours are preserved, including the blue sky and golden vines; this selection is not converted to monochrome green.\n\nThe original 1448 × 1086 board is cropped at **(979, 122) to 450 × 600, exactly 3:4**. The crop removes captions, gutters and excess lower vineyard while keeping the dragon head, horns, claws, village and vineyard rows. Uniform Lanczos downsampling gives a 300 × 400 AVIF (quality 65, 4:4:4), wrapped with the shared 26-unit corner clipping and 1% bleed. There is no stretching, regeneration, repainting or recolouring. The source and runtime SVGs are byte-identical and need no additional fit override.\n\n`docs/design/van-gogh/green-dragon-vineyard.json` records selection, crop and image checksums. The untouched board, full selected panel and lossless 3:4 crop are preserved in `Van_Gogh_Green_Dragon_Vineyard_C_Approved.zip`, supplied in chat. The repository SVG embeds the game-sized image, not the full-resolution original.\n\nRun `node web/scripts/export-van-gogh-tiles.mjs --only=6z` to reproduce this face, registry, manifest and gallery without rewriting other artwork. This addition brings the set to **31 painted faces and 3 named fallbacks**. Every prior painting, proportion fit and manifest entry, the fourteen-tile sample hand and gameplay remain unchanged.\n'''
doc=read('docs/design/van-gogh/README.md')
doc=once(doc,'**Current set:** 30 painted faces and 4 unpainted identities showing their names.','**Current set:** 31 painted faces and 3 unpainted identities showing their names. Green Dragon at the Vineyard C is active for green dragon (6z).')
put('docs/design/van-gogh/README.md',doc.rstrip()+'\n'+section)
doc=read('web/public/tiles/van-gogh/README.md')
doc=once(doc,'The 30 approved faces','The 31 approved faces')
doc=once(doc,'The other 4 identities awaiting Van Gogh artwork','The other 3 identities awaiting Van Gogh artwork')
doc=once(doc,'**Lemons by the Sea** is active','**Green Dragon at the Vineyard C** is active for green dragon (6z / Hatsu). **Lemons by the Sea** is active')
put('web/public/tiles/van-gogh/README.md',doc.rstrip()+'\n'+section)
subprocess.run(['node',export_path,'--only=6z'],check=True)
current=json.loads(read(manifest_path))
assert len(current['tiles'])==31
assert current['remaining']==['1m','2z','3z']
by_tile={t['tile']:t for t in current['tiles']}
for entry in previous['tiles']: assert by_tile[entry['tile']]==entry,entry['tile']
by_source={s['id']:s for s in current['sources']}
for entry in previous['sources']: assert by_source[entry['id']]==entry,entry['id']
assert hand(read('web/public/tiles/van-gogh/preview.html'))==old_hand
for p,h in preserved.items(): assert sha((root/p).read_bytes())==h,p
entry=by_tile['6z']
assert entry['svgSha256']==provenance['svgSha256']
assert entry['rasterMimeType']=='image/avif'
assert (root/provenance['runtime']).read_bytes()==svg.encode()
output_paths=[manifest_path,'web/src/lib/van-gogh-faces.js','web/public/tiles/van-gogh/preview.html',provenance['runtime']]
outputs={p:sha((root/p).read_bytes()) for p in output_paths}
subprocess.run(['node',export_path,'--only=6z'],check=True)
for p,h in outputs.items(): assert sha((root/p).read_bytes())==h,p
for p,h in preserved.items(): assert sha((root/p).read_bytes())==h,p
print(f'PRESERVED {len(preserved)} prior artwork/source files and {len(previous["tiles"])} prior manifest entries, including all proportion fits.')
print('VERIFIED: exact Vineyard C binary, 3:4 crop provenance, registration, unchanged fourteen-tile hand, and byte-identical repeated selective export. 31 painted / 3 remaining.')
