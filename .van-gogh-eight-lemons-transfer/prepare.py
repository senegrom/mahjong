"""Install the approved eight-lemon source, preserving all pre-existing art."""
from pathlib import Path
import base64
import hashlib
import json
import re
import subprocess

root = Path.cwd()
transfer = root / '.van-gogh-eight-lemons-transfer'
record = json.loads((transfer / 'eight-disks-lemons.json').read_text())
manifest_path = root / 'web/public/tiles/van-gogh/manifest.json'
before = json.loads(manifest_path.read_text())
assert '8p' in before['remaining'], '8 disks is already painted; review the concurrent selection'
assert not any(e['tile'] == '8p' for e in before['tiles'])
assert next(e for e in before['tiles'] if e['tile'] == '7p')['candidate'] == 'Seven Apples (corrected)'
assert next(e for e in before['tiles'] if e['tile'] == '9p')['candidate'] == 'Disks C'
hash_bytes = lambda data: hashlib.sha256(data).hexdigest()
tracked = subprocess.check_output(['git', 'ls-files', '-z']).decode().split('\0')
images = {p: hash_bytes((root / p).read_bytes()) for p in tracked if p and Path(p).suffix.lower() in {'.png', '.svg', '.webp', '.avif', '.jpg', '.jpeg'}}
parts = [transfer / f'part{i:02d}.bin' for i in range(6)]
raster = b''.join(p.read_bytes() for p in parts)
assert len(raster) == record['rasterBytes'] == 69178
assert hash_bytes(raster) == record['rasterSha256'] == 'b97d16c560e0d88b8155e42ed0bc90b35bc48e0357df88d4569bec3986afb757'
assert raster[:4] == b'RIFF' and raster[8:16] == b'WEBPVP8 '
assert (int.from_bytes(raster[26:28], 'little') & 0x3fff, int.from_bytes(raster[28:30], 'little') & 0x3fff) == (300, 400)
svg = ('<svg xmlns="http://www.w3.org/2000/svg" width="300" height="400" viewBox="0 0 300 400" role="img" aria-labelledby="title"><title id="title">Eight disks — Van Gogh</title><defs><clipPath id="face"><rect width="300" height="400" rx="26"/></clipPath></defs><image clip-path="url(#face)" x="-3" y="-4" width="306" height="408" preserveAspectRatio="none" href="data:image/webp;base64,' + base64.b64encode(raster).decode() + '"/></svg>\n').encode()
assert hash_bytes(svg) == record['svgSha256'] == 'f0d9ed90074049d1db9ebee3731351bf025cd55d9bc296f279941b4ef8618864'
for relative in (record['source'], record['runtime'], 'docs/design/van-gogh/eight-disks-lemons.json'):
    assert not (root / relative).exists(), f'Refusing to overwrite {relative}'


def once(text, old, new):
    assert text.count(old) == 1, f'Patch anchor changed: {old!r}'
    return text.replace(old, new, 1)


export_path = root / 'web/scripts/export-van-gogh-tiles.mjs'
export = export_path.read_text()
export = once(export, '\n};\nconst definitions = [', "\n  eightLemons: '" + record['source'] + "',\n};\nconst definitions = [")
export = once(export, '\n];\nconst onlyArgument =', "\n  ['Eight Lemons', '8p', 'Eight disks', 'eightLemons', [0, 0, 300, 400]],\n];\nconst onlyArgument =")
export = once(export, "',\n  fallback:", " Carl approved the standalone Lemons by the Sea painting with exactly eight lemons arranged 3-2-3 for 8 disks and explicitly requested GitHub deployment. The complete 3:4 composition is proportionally downsampled without repainting or recolouring; Seven Apples 7p and The Potter’s Table 9p are unchanged.',\n  fallback:")
export = once(export, '// Generated by web/scripts/export-van-gogh-tiles.mjs. Includes ', '// Generated by web/scripts/export-van-gogh-tiles.mjs. Includes Lemons by the Sea (8p), completing the disks suit, ')
export = once(export, 'const featured = [', "const featured = ['8p', ")
export = once(export, '${approved.length} approved faces, including ', '${approved.length} approved faces, including Lemons by the Sea for 8 disks, ')

# Append only to the Van Gogh snapshots; never replace another artist's list.
test_path = root / 'web/tests/tile-faces.test.js'
tests = test_path.read_text()
match = re.search(r"(const approved = \[)([^\n]*)(\];)", tests)
assert match and "'7p'" in match[2] and "'8p'" not in match[2]
tests = tests[:match.start()] + match[1] + match[2] + ", '8p'" + match[3] + tests[match.end():]
match = re.search(r"(assert\.deepEqual\(set\.tiles\.map\(tile => tile\.candidate\), \[)([^\n]*)(\]\);)", tests)
assert match and "'Seven Apples (corrected)'" in match[2] and "'Eight Lemons'" not in match[2]
tests = tests[:match.start()] + match[1] + match[2] + ", 'Eight Lemons'" + match[3] + tests[match.end():]

new_count = len(before['tiles']) + 1
new_missing = len(before['remaining']) - 1
section = f'''\n## Lemons by the Sea — 8 disks\n\nCarl approved the standalone painting of **eight lemons in a 3–2–3 arrangement** for `8p` / `Pin8`. It completes the disks suit. Seven Apples for 7 disks, The Potter’s Table for 9 disks and all other artwork remain unchanged.\n\nThe entire 1086 × 1448 original is exactly 3:4 and was proportionally downsampled to 300 × 400 with Lanczos, then encoded as quality-90 WebP. There is no repainting, recolouring or compositional crop; the game uses its standard 26-unit rounded corners and 1% bleed. This is an optimized game export, not a lossless full-resolution original. The original PNG is preserved in `van-gogh-eight-disks-lemons-original.zip` supplied in chat.\n\nThe source and runtime SVGs are identical. Original, raster and SVG checksums are recorded in `docs/design/van-gogh/eight-disks-lemons.json`. Reproduce only this face with `node web/scripts/export-van-gogh-tiles.mjs --only=8p`. The set now has **{new_count} painted faces and {new_missing} unpainted identities showing their names**.\n'''
docs = {}
for relative in ('docs/design/van-gogh/README.md', 'web/public/tiles/van-gogh/README.md'):
    text = (root / relative).read_text()
    text = once(text, '8 disks and all other tiles are unchanged. Earlier sections', 'That restoration left the other tiles unchanged. Eight disks now uses Lemons by the Sea. Earlier sections')
    if relative.startswith('docs/'):
        text, count = re.subn(r'^\*\*Current set:\*\*[^\n]*', f'**Current set:** {new_count} painted faces and {new_missing} unpainted identities showing their names. Lemons by the Sea is active for 8 disks; both the disks and bamboo suits are complete. Poppy Field with smaller 萬 for 9 characters and all prior selections remain unchanged. Earlier sections retain historical counts.', text, count=1, flags=re.M)
        assert count == 1
    else:
        text, count = re.subn(r'(The )\d+( approved faces appear)', lambda m: m[1] + str(new_count) + m[2], text, count=1)
        assert count == 1
        text, count = re.subn(r'(The other )\d+( identities awaiting Van Gogh artwork)', lambda m: m[1] + str(new_missing) + m[2], text, count=1)
        assert count == 1
        text = once(text, 'The selected studies are ', '**Lemons by the Sea** is active for 8 disks, completing all nine disks. The selected studies are ')
    docs[relative] = text + section

# All bytes and edit anchors were checked before the first repository write.
(root / record['source']).write_bytes(svg)
(root / 'docs/design/van-gogh/eight-disks-lemons.json').write_text(json.dumps(record, ensure_ascii=False, indent=2) + '\n')
export_path.write_text(export)
test_path.write_text(tests)
for relative, text in docs.items():
    (root / relative).write_text(text)
command = ['node', 'web/scripts/export-van-gogh-tiles.mjs', '--only=8p']
subprocess.run(command, check=True)
after = json.loads(manifest_path.read_text())
assert after['tiles'][:-1] == before['tiles'], 'An existing tile entry changed'
assert after['sources'][:-1] == before['sources'], 'An existing source entry changed'
assert after['remaining'] == [t for t in before['remaining'] if t != '8p']
assert after['rejected'] == before['rejected'] and after['superseded'] == before['superseded']
assert after['fallback'] == before['fallback'] == 'text'
assert len(after['tiles']) == new_count and len(after['remaining']) == new_missing
assert after['tiles'][-1]['tile'] == '8p' and after['tiles'][-1]['svgSha256'] == record['svgSha256']
assert 'fit' not in after['tiles'][-1], 'Already 3:4 artwork should not be distorted'
assert (root / record['runtime']).read_bytes() == svg
for relative, checksum in images.items():
    assert hash_bytes((root / relative).read_bytes()) == checksum, f'Existing artwork changed: {relative}'
preview = (root / 'web/public/tiles/van-gogh/preview.html').read_text()
rack = re.search(r'<div class="rack" id="rack">(.*?)</div>', preview).group(1)
assert rack.count('<img ') == 14 and 'approved/Pin8.svg' in rack
assert 'Lemons by the Sea for 8 disks' in preview
outputs = [record['runtime'], 'web/public/tiles/van-gogh/manifest.json', 'web/public/tiles/van-gogh/preview.html', 'web/src/lib/van-gogh-faces.js']
first = {p: (root / p).read_bytes() for p in outputs}
subprocess.run(command, check=True)
assert all((root / p).read_bytes() == data for p, data in first.items()), 'Non-deterministic export'
print(f'PASS: exact eight-lemon transfer; {len(images)} existing artwork files and {len(before["tiles"])} previous tile entries unchanged; {new_count} painted / {new_missing} unpainted; complete disks and bamboo; deterministic export; 14-tile preview.')
