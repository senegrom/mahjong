const facesTestPath = 'web/tests/tile-faces.test.js';
let facesTest = read(facesTestPath).toString();
facesTest = replaceOnce(facesTest, 'Dali resolves twenty-one approved images', 'Dali resolves twenty-two approved images');
facesTest = replaceOnce(facesTest, "new Set(['1p', '3p', '4p', '5p'", "new Set(['1p', '2p', '3p', '4p', '5p'");
facesTest = replaceOnce(facesTest, "['4p', '3s', '4s'].includes(tile)", "['2p', '4p', '3s', '4s'].includes(tile)");
