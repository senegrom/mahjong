import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, readdirSync, mkdirSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import path from 'node:path';

const base = '4374bc0db52f0fbc0949f0b9b497b79a41c45f40';
const stage = '.art-import/two-balance';
const read = file => readFileSync(file);
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const git = args => execFileSync('git', args, { encoding: 'utf8' }).trim();
const tracked = git(['ls-files', '-z', 'web/public/tiles', 'docs/design']).split('\0').filter(Boolean);
const oldArt = new Map(tracked.filter(file => /\.(?:png|svg|avif|webp|jpe?g)$/i.test(file)).map(file => [file, hash(read(file))]));
const manifestPath = 'web/public/tiles/dali/manifest.json';
const oldManifest = JSON.parse(read(manifestPath));
assert.equal(oldManifest.tiles.length, 21);
assert.equal(oldManifest.placeholders.length, 13);
assert.equal(oldManifest.fallback, 'text');
assert.equal(oldManifest.tiles.some(entry => entry.tile === '2p'), false);
const metadata = JSON.parse(read(`${stage}/metadata.json`));
const parts = Array.from({ length: 9 }, (_, n) => read(`${stage}/part${String(n).padStart(2, '0')}.bin`));
const raster = Buffer.concat(parts);
assert.equal(raster.length, 96680);
assert.equal(hash(raster), metadata.rasterSha256);
assert.equal(raster.toString('ascii', 4, 12), 'ftypavif');
const ispe = raster.indexOf(Buffer.from('ispe'));
assert.ok(ispe >= 0);
assert.deepEqual([raster.readUInt32BE(ispe + 8), raster.readUInt32BE(ispe + 12)], [1086, 1448]);
const markup = `<svg xmlns="http://www.w3.org/2000/svg" width="300" height="400" viewBox="0 0 300 400" role="img" aria-labelledby="title"><title id="title">2 disks — Dali — The Impossible Balance — B</title><metadata>${JSON.stringify(metadata)}</metadata><defs><clipPath id="face"><rect width="300" height="400" rx="26"/></clipPath></defs><image clip-path="url(#face)" x="-3" y="-4" width="306" height="408" preserveAspectRatio="none" href="data:image/avif;base64,${raster.toString('base64')}"/></svg>\n`;
const svgHash = hash(markup);
assert.equal(svgHash, '309cf800d3679cdad4943bfdb6eb580320927d26bfd4ef1f74b69ab9de394601');
for (const [file, bytes] of [[metadata.rasterSource, raster], [metadata.source, markup], [metadata.runtime, markup]]) {
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, bytes);
}
writeFileSync('docs/design/dali/two-disks.json', JSON.stringify({ ...metadata, svgSha256: svgHash }, null, 2) + '\n');
const manifest = structuredClone(oldManifest);
const entry = { name: 'Pin2', tile: '2p', label: '2 disks', direction: metadata.direction, status: 'approved', svg: 'approved/Pin2.svg', source: metadata.source, sourceSha256: svgHash, svgSha256: svgHash, crop: { x: 0, y: 0, width: 1086, height: 1448 } };
manifest.tiles.splice(manifest.tiles.findIndex(tile => tile.tile === '1p') + 1, 0, entry);
manifest.placeholders = manifest.placeholders.filter(tile => tile.tile !== '2p');
writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
writeFileSync('web/src/lib/dali-faces.js', `// Generated by web/scripts/export-dali-tiles.mjs.\nexport const DALI_APPROVED = Object.freeze(${JSON.stringify(manifest.tiles.map(tile => tile.tile))});\n`);

const replaceOnce = (text, before, after) => {
  assert.equal(text.split(before).length - 1, 1, `Expected one occurrence: ${before}`);
  return text.replace(before, after);
};
const exporterPath = 'web/scripts/export-dali-tiles.mjs';
let exporter = read(exporterPath).toString();
exporter = replaceOnce(exporter, "  ['Pin3',", "  ['Pin2', '2p', '2 disks', 'The Impossible Balance — B', 'two-disks-b-approved.svg', [0, 0, 1086, 1448]],\n  ['Pin3',");
exporter = replaceOnce(exporter, '${manifest.tiles.length} approved faces. ', '${manifest.tiles.length} approved faces. Two disks uses B — The Impossible Balance: the approved middle painting with a sapphire disk high on a soft ivory branch and a jade disk low over the salt flat, while the shadow remains a rigid straight beam. Ranks 1–5 of disks are complete. ');
exporter = replaceOnce(exporter, "'Pin4', 'Sou6'", "'Pin4', 'Pin2'");
writeFileSync(exporterPath, exporter);
const previewStart = exporter.indexOf('const cards = ');
assert.ok(previewStart > 0);
new Function('manifest', 'out', 'path', 'writeFileSync', exporter.slice(previewStart))(
  manifest, 'web/public/tiles/dali', path, writeFileSync,
);

const readmePath = 'docs/design/dali/README.md';
let readme = read(readmePath).toString();
readme = replaceOnce(readme, 'Twenty-one faces are approved', 'Twenty-two faces are approved');
readme = replaceOnce(readme, 'The latest is four disks', 'The latest is two disks **The Impossible Balance — B**, the selected middle painting with two jewel-toned medallions on a soft ivory branch and a rigid straight shadow. This completes ranks 1–5 of disks. The previously selected four disks');
readme = replaceOnce(readme, '| `Pin3.svg`', '| `Pin2.svg` | 2 disks | The Impossible Balance — B: a sapphire disk high on a melting ivory branch and a jade disk low over the salt flat; their shadow stays rigid and straight |\n| `Pin3.svg`');
readme = replaceOnce(readme, 'The other 13 tiles', 'The other 12 tiles');
readme = readme.replaceAll('twenty-one approved faces', 'twenty-two approved faces');
