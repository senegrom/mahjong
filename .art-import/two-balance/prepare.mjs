execFileSync('npx', ['--no-install', 'eslint', 'scripts/export-dali-tiles.mjs', ...[...changedTests, facesTestPath, newTest].map(file => file.replace(/^web\//, '')), '--max-warnings', '0'], { cwd: 'web', stdio: 'inherit' });

rmSync(stage, { recursive: true });
rmSync('.github/workflows/prepare-dali-two-balance.yml');
